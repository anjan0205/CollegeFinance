-- ============================================================================
-- College Budget & PR Management System
-- Database Schema Definition (Oracle DDL)
-- File: 01_schema.sql
-- ============================================================================

-- 1. DEPARTMENTS TABLE
CREATE TABLE DEPARTMENTS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR2(20) NOT NULL UNIQUE,
    name VARCHAR2(100) NOT NULL,
    category VARCHAR2(50) DEFAULT 'Academic' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. USERS TABLE
CREATE TABLE USERS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(30) DEFAULT 'DEPARTMENT_USER' NOT NULL,
    department_id NUMBER,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_department FOREIGN KEY (department_id) REFERENCES DEPARTMENTS(id) ON DELETE SET NULL
);

-- 3. BUDGET_HEADS TABLE
CREATE TABLE BUDGET_HEADS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code NUMBER NOT NULL UNIQUE,
    name VARCHAR2(200) NOT NULL,
    category VARCHAR2(50) DEFAULT 'Recurring' NOT NULL,
    description VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 4. BUDGET_ALLOCATIONS TABLE
CREATE TABLE BUDGET_ALLOCATIONS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id NUMBER NOT NULL,
    budget_head_id NUMBER NOT NULL,
    source_budget_code VARCHAR2(50) NOT NULL,
    financial_year VARCHAR2(20) DEFAULT '2026-27' NOT NULL,
    allocated_amount NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    committed_amount NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    actual_utilized_amount NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_alloc_dept FOREIGN KEY (department_id) REFERENCES DEPARTMENTS(id) ON DELETE CASCADE,
    CONSTRAINT fk_alloc_head FOREIGN KEY (budget_head_id) REFERENCES BUDGET_HEADS(id) ON DELETE CASCADE,
    CONSTRAINT uq_dept_head_fy UNIQUE (department_id, budget_head_id, financial_year)
);

-- 5. PRS (Purchase Requisitions Header) TABLE
CREATE TABLE PRS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pr_number VARCHAR2(50) NOT NULL UNIQUE,
    pr_date DATE NOT NULL,
    department_id NUMBER NOT NULL,
    budget_head_id NUMBER NOT NULL,
    requested_by VARCHAR2(150) NOT NULL,
    purpose CLOB,
    total_amount NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    status VARCHAR2(30) DEFAULT 'Open' NOT NULL,
    approval_status VARCHAR2(30) DEFAULT 'Pending' NOT NULL,
    pr_po_status VARCHAR2(30) DEFAULT 'Open' NOT NULL,
    approval_1 VARCHAR2(500),
    approval_2 VARCHAR2(500),
    approval_3 VARCHAR2(500),
    source_budget_code VARCHAR2(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_prs_dept FOREIGN KEY (department_id) REFERENCES DEPARTMENTS(id),
    CONSTRAINT fk_prs_head FOREIGN KEY (budget_head_id) REFERENCES BUDGET_HEADS(id)
);

-- 6. PR_ITEMS (Purchase Requisition Line Items) TABLE
CREATE TABLE PR_ITEMS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pr_id NUMBER NOT NULL,
    product_name VARCHAR2(255) NOT NULL,
    product_code VARCHAR2(100),
    product_type VARCHAR2(50) DEFAULT 'goods',
    product_description CLOB,
    unit_type_name VARCHAR2(50) DEFAULT 'Numbers',
    quantity NUMBER(12, 3) DEFAULT 1 NOT NULL,
    unit_price NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    total_value NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    current_stock NUMBER(12, 3) DEFAULT 0,
    preferred_vendor VARCHAR2(255),
    product_required_by DATE,
    item_remarks CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_pr_items_pr FOREIGN KEY (pr_id) REFERENCES PRS(id) ON DELETE CASCADE
);

-- 7. EXPENDITURES TABLE
CREATE TABLE EXPENDITURES (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pr_id NUMBER NOT NULL,
    department_id NUMBER NOT NULL,
    budget_head_id NUMBER NOT NULL,
    expenditure_date DATE DEFAULT SYSDATE NOT NULL,
    amount NUMBER(15, 2) NOT NULL,
    payment_status VARCHAR2(30) DEFAULT 'Paid' NOT NULL,
    remarks VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_exp_pr FOREIGN KEY (pr_id) REFERENCES PRS(id),
    CONSTRAINT fk_exp_dept FOREIGN KEY (department_id) REFERENCES DEPARTMENTS(id),
    CONSTRAINT fk_exp_head FOREIGN KEY (budget_head_id) REFERENCES BUDGET_HEADS(id)
);

-- 8. IMPORT_BATCHES TABLE
CREATE TABLE IMPORT_BATCHES (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_type VARCHAR2(30) NOT NULL, -- 'BUDGET' or 'PR'
    filename VARCHAR2(255) NOT NULL,
    total_rows NUMBER DEFAULT 0 NOT NULL,
    imported_count NUMBER DEFAULT 0 NOT NULL,
    updated_count NUMBER DEFAULT 0 NOT NULL,
    skipped_count NUMBER DEFAULT 0 NOT NULL,
    error_count NUMBER DEFAULT 0 NOT NULL,
    imported_by NUMBER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_import_user FOREIGN KEY (imported_by) REFERENCES USERS(id) ON DELETE SET NULL
);

-- 9. IMPORT_ERRORS TABLE
CREATE TABLE IMPORT_ERRORS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id NUMBER NOT NULL,
    row_number NUMBER NOT NULL,
    pr_number VARCHAR2(50),
    error_message VARCHAR2(1000) NOT NULL,
    raw_data CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_errors_batch FOREIGN KEY (batch_id) REFERENCES IMPORT_BATCHES(id) ON DELETE CASCADE
);

-- 10. AUDIT_LOGS TABLE
CREATE TABLE AUDIT_LOGS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER,
    action VARCHAR2(100) NOT NULL,
    entity_type VARCHAR2(50) NOT NULL,
    entity_id VARCHAR2(50),
    details CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES USERS(id) ON DELETE SET NULL
);
